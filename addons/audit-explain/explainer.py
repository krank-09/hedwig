"""
Plain-language explanations of audit records, generated by Google Gemini and saved.

Part of the HEDWIG audit-explain add-on (see README.md). It works on a signed audit record
exactly as the HEDWIG server returns it from GET /api/audit/{id}; it imports nothing from HEDWIG.

Raw audit records are long and full of hashes, keys and internal parameters, and some fields look
contradictory unless you know the format (e.g. the policy "response" can be WATCH while an
independent probe quarantined one hop). So Gemini is not sent the raw record. `facts()` turns it
into a short digest with readable names, and the prompt is a field guide for reading it.

    GEMINI_API_KEY        required; without it the feature reports itself unavailable (HTTP 503)
    GEMINI_MODEL          optional; defaults to DEFAULT_MODEL
    HEDWIG_EXPLANATIONS   optional path of the saved explanations (JSON); defaults to
                          data/audit_explanations.json in this folder (gitignored)

Private evidence (elimination tables, keep/forward choices, events) is never sent. If the record
includes evidence (HEDWIG only returns it to admins), the digest adds only per-route test counts
and hop names from it. Explanations are saved per (artifact, model, prompt version, digest) and
reused across restarts. A truncated answer is an error and is never saved. Standard library only.
"""
import asyncio
import datetime as dt
import hashlib
import json
import os
import re
import tempfile
import threading
import time
import urllib.error
import urllib.request
from typing import Any, Dict, Optional

DEFAULT_MODEL = "gemini-2.5-flash"
PROMPT_VERSION = "3"
ENDPOINT = "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
TIMEOUT_S = 30
MAX_FACTS_CHARS = 12_000
MAX_OUTPUT_TOKENS = 2048

INSTRUCTIONS = """You explain audit records from HEDWIG to people with no background in cryptography,
statistics or quantum physics. You are given a FACTS digest of one signed audit record, not the
raw record.

What HEDWIG is: a simulated quantum digital signature system. Alice signs a message and sends
"quantum tokens" to two verifiers, Bob and Charlie, through a relay (e.g. QR-1). Some tokens are
secret "test tokens": if too many come out wrong, someone may be listening in. Only if the tests
pass does Alice reveal her signature for Bob and Charlie to check. A "circuit breaker" protects
links: OPEN (normal) -> WATCH (suspicious; extra checks, more strikes escalate) -> QUARANTINED
(blocked until an administrator resets it, then on probation). Each decision becomes a digitally
signed record, chained to the previous one so tampering would show.

How to read the FACTS:
- final_outcome: the verdict on this message. "distribution_aborted" means the system stopped
  BEFORE the signature was revealed. Nothing was signed off and nothing was forged; it is a
  protective stop.
- policy_response: what the rules decided for the signer's link (accept, WATCH or QUARANTINE),
  with evidence_p.
- link_changes: what actually changed, on which link, and who triggered it. This can differ from
  policy_response. Example: the response is WATCH (evidence was weak) while an independent probe
  of one hop quarantined just that hop. Explain both and why they differ.
- independent probe: after a suspicious result, the system re-tests each hop of the route
  separately with fresh test tokens, to find which hop is faulty.
- overall_channel_test vs per_route_tests: the overall test pools every recipient. A per-route
  test looks at one recipient's path. A problem on one path can trip its route test while the
  pooled test does not alarm. If so, say that the problem was on that path.
- wrong share / QBER: the fraction of test tokens that came out wrong. Honest links are expected
  around 2% or less; full eavesdropping gives about 25%.
- evidence_p / p_value: the chance of seeing results this bad if nothing were wrong. Translate it,
  e.g. p = 0.0044 is "about a 1 in 230 chance of happening by accident". Below 0.001 counts as
  decisive; higher is suspicious but not conclusive.
- hops are written "A->B" (e.g. "QR-1->bob" is the link from relay QR-1 to Bob).
- the message text is never stored, only a fingerprint of it.

Write for a layperson:
1. One opening sentence: what happened, and whether it is good news, bad news or a safe stop.
2. Then 3 to 6 short bullets (start each with "- "): who was involved, what was checked and what
   was found (use the actual numbers, e.g. "3 of Bob's 17 test tokens came back wrong"), what the
   system did, and what happens next or what an administrator should do.
3. End with one line starting "Why it matters:".

Rules: use only facts in the digest; never invent numbers, names, times or outcomes. If something
is missing or unclear, say so briefly. No jargon without a few-word explanation. No hashes, key IDs
or field names. Do not say the simulation is real hardware. Under 190 words. Plain text only.

Example of the style (for a different, accepted record):
Alice's message was checked and accepted by both verifiers, with no sign of eavesdropping.
- Bob and Charlie each received their tokens through relay QR-1.
- Before anything was revealed, 34 secret test tokens were checked and none came back wrong.
- Alice then revealed her signature; both verifiers found it matched their own measurements.
- All links stay open; nothing needs to be done.
Why it matters: the message really came from Alice and was not altered on the way."""


class ExplainUnavailable(RuntimeError):
    """The feature is not configured (no API key)."""


class ExplainFailed(RuntimeError):
    """Gemini could not produce a complete explanation."""


# ------------------------------------------------------------------ facts digest

HEX64 = re.compile(r"\b[0-9a-f]{64}\b")
# Internal or cryptographic detail with nothing for a layperson (or already summarised elsewhere).
DROP = {
    "canonicalization", "nonce", "created_at", "expires_at", "evidence_digests", "disclaimers",
    "signature_suite", "bounds", "parameters", "policy", "simulator", "routing", "fidelity",
    "chain", "version", "protocol_version", "format", "payload_sha256", "signatures",
    "public_keys", "evidence", "key_id", "topology_digest", "plan_sha256", "execution_sha256",
    "evidence_id", "policy_version", "ts", "event_ids", "events_in_this_record", "later_events",
    "chernoff_kl_bound", "exact_false_alarm_level", "detection_power_at_25pct", "strong_alpha",
    "strong_threshold_errors", "honest_qber_assumption", "false_alarm_alpha", "planned_test_count",
    "issued_at", "message", "session", "verifiers", "transmission_id", "session_id", "kind",
    "outcome", "response", "enforcement", "channel_test", "assurance", "tier2", "verification_summary",
}


def _when(ts: Any) -> Optional[str]:
    try:
        return dt.datetime.fromtimestamp(float(ts), dt.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    except (TypeError, ValueError):
        return None


def _hop_names(cert: Dict[str, Any], include_evidence: bool) -> Dict[str, str]:
    """'edge:<sha256>' -> 'QR-1->bob', from the route plan (admins) or the attribution text."""
    names: Dict[str, str] = {}
    if include_evidence:
        plan = (((cert.get("evidence") or {}).get("routing") or {}).get("plan") or {})
        for name, scope in (plan.get("edge_scope_map") or {}).items():
            names[scope] = name
    enf = (cert.get("record") or {}).get("enforcement") or {}
    m = re.search(r"([\w.-]+->[\w.-]+)\s*$", str(enf.get("attribution") or ""))
    if m and isinstance(enf.get("link"), str) and enf["link"].startswith("edge:"):
        names.setdefault(enf["link"], m.group(1))
    return names


def _readable(value: Any, names: Dict[str, str]) -> Any:
    """Drop noise keys, rename hops, hide remaining hashes, shorten long lists, recursively."""
    if isinstance(value, dict):
        out = {k: _readable(v, names) for k, v in value.items() if k not in DROP and v not in (None, {}, [])}
        return {k: v for k, v in out.items() if v not in (None, {}, [])}
    if isinstance(value, list):
        items = [_readable(v, names) for v in value[:12]]
        return items + ([f"... {len(value) - 12} more"] if len(value) > 12 else [])
    if isinstance(value, str):
        if value in names:
            return names[value]
        if value.startswith("path:"):
            return "a route"
        return HEX64.sub("(fingerprint)", value)
    return value


def _test_summary(t: Optional[Dict[str, Any]]) -> Optional[Dict[str, Any]]:
    if not t or t.get("test_count") is None:
        return None
    out = {
        "test_tokens": t.get("test_count"),
        "came_back_wrong": t.get("error_count"),
        "wrong_share": t.get("qber_estimate"),
        "alarm": t.get("alarm"),
        "alarm_if_more_than": t.get("alarm_threshold_errors"),
        "p_value": t.get("p_value"),
    }
    if t.get("tokens_sent") is not None:
        out["tokens_sent_received_lost"] = [t.get("tokens_sent"), t.get("tokens_received"), t.get("tokens_lost")]
    if t.get("qber_ci_low") is not None and t.get("qber_ci_high") is not None:
        out["wrong_share_interval"] = [t["qber_ci_low"], t["qber_ci_high"]]
    if t.get("early_abort"):
        out["stopped_early"] = True
    return {k: v for k, v in out.items() if v is not None}


def facts(cert: Dict[str, Any], include_evidence: bool = False) -> Dict[str, Any]:
    """A short, readable digest of an audit certificate for the explanation prompt."""
    rec = cert.get("record") or {}
    names = _hop_names(cert, include_evidence)
    out: Dict[str, Any] = {
        "record_type": rec.get("kind"),
        "id": rec.get("transmission_id") or rec.get("incident_id") or rec.get("artifact_id"),
        "time": _when(rec.get("issued_at")),
        "digitally_signed_with": [
            s.get("algorithm") + (" (post-quantum)" if s.get("post_quantum") else "")
            for s in rec.get("signature_suite") or [] if s.get("algorithm")
        ],
    }
    if rec.get("verifiers"):
        out["verifiers"] = rec["verifiers"]
    sess = rec.get("session") or {}
    if sess.get("participants"):
        out["per_verifier_status"] = {p.get("verifier"): p.get("status") for p in sess["participants"]}
    checks = {}
    for key, v in (rec.get("verification_summary") or {}).items():
        if not isinstance(v, dict):
            continue
        name, _, mode = str(key).partition("/")  # e.g. "bob/direct", "charlie/forwarded"
        label = name if mode in ("", "direct") else f"{name} ({mode})"
        passed = {k: x for k, x in (v.get("checks") or {}).items() if isinstance(x, bool)}
        row = {"verifier": name, "delivery": mode or None, "accepted": v.get("accepted"),
               "mismatches": v.get("mismatches"), "copies_checked": v.get("checked"),
               "accept_if_at_most": v.get("limit"), "forwarded_by": v.get("forwarded_by"),
               "checks_passed": passed or None}
        checks[label] = {k: x for k, x in row.items() if x is not None}
    if checks:
        out["verifier_checks"] = checks
    if (rec.get("message") or {}).get("digest"):
        out["message"] = "only a fingerprint of the message is stored, not its text"
    for key, label in (("outcome", "final_outcome"), ("response", "policy_response"), ("tier2", "attribution_test")):
        if rec.get(key):
            out[label] = _readable(rec[key], names)
    enf = rec.get("enforcement") or {}
    if enf:
        change = {
            "action": enf.get("action"),
            "link": names.get(enf.get("link"), enf.get("link")),
            "link_state_before": (enf.get("transition") or {}).get("old_state"),
            "link_state_now": enf.get("link_state"),
            "triggered_by": (enf.get("transition") or {}).get("actor"),
            "reason": (enf.get("transition") or {}).get("reason"),
            "located": enf.get("attribution"),
            "incident": enf.get("incident_id"),
        }
        out["link_changes"] = _readable({k: v for k, v in change.items() if v}, names)
    if _test_summary(rec.get("channel_test")):
        out["overall_channel_test"] = _test_summary(rec.get("channel_test"))
    if include_evidence:
        execution = (((cert.get("evidence") or {}).get("routing") or {}).get("execution") or {})
        routes = {r: _test_summary(t) for r, t in (execution.get("route_tests") or {}).items()}
        if any(routes.values()):
            out["per_route_tests"] = {r: t for r, t in routes.items() if t}
        if execution.get("abort_reason"):
            out["stopped_because"] = execution["abort_reason"]
    if (rec.get("assurance") or {}).get("level"):
        out["assurance"] = rec["assurance"]["level"]
    if (rec.get("chain") or {}).get("seq") is not None:
        out["record_number_in_chain"] = rec["chain"]["seq"]
    suite = rec.get("signature_suite") or []
    if suite:
        out["post_quantum_signature"] = any(s.get("post_quantum") for s in suite)
    timing = {}
    try:
        created, issued = float(rec["created_at"]), float(rec["issued_at"])
        timing["started"] = _when(created)
        timing["record_issued_after_ms"] = round((issued - created) * 1000, 1)
        if rec.get("expires_at") is not None:
            timing["freshness_window_s"] = round(float(rec["expires_at"]) - created, 1)
    except (KeyError, TypeError, ValueError):
        pass
    if timing:
        out["timing"] = timing
    fid = rec.get("fidelity") or {}
    if isinstance(fid.get("estimate"), (int, float)):
        out["fidelity_estimate"] = {"estimate": fid["estimate"], "interval": fid.get("ci95"),
                                    "note": "model-based estimate, not a direct measurement"}
    params = rec.get("parameters") or {}
    rules = {"honest_wrong_share_assumed": params.get("honest_qber_e0"),
             "false_alarm_rate": params.get("false_alarm_alpha"),
             "decisive_evidence_level": params.get("strong_alpha")}
    rules = {k: v for k, v in rules.items() if v is not None}
    if rules:
        out["rules_used"] = rules
    # Anything else in the record (other record kinds: incident, link_reset, transfer, probes ...).
    rest = _readable({k: v for k, v in rec.items() if k not in DROP}, names)
    if rest:
        out["other_details"] = rest
    return {k: v for k, v in out.items() if v not in (None, {}, [])}


# ------------------------------------------------------------------ saved explanations

_lock = threading.Lock()
_saved: Optional[Dict[str, Dict[str, Any]]] = None
_saved_path: Optional[str] = None


def store_path() -> str:
    explicit = os.environ.get("HEDWIG_EXPLANATIONS", "").strip()
    if explicit:
        return explicit
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "audit_explanations.json")


def _load() -> Dict[str, Dict[str, Any]]:
    """Saved explanations, loaded once per path."""
    global _saved, _saved_path
    path = store_path()
    if _saved is None or _saved_path != path:
        try:
            with open(path, encoding="utf-8") as f:
                _saved = json.load(f)
        except (FileNotFoundError, json.JSONDecodeError):
            _saved = {}
        _saved_path = path
    return _saved


def _persist(entries: Dict[str, Dict[str, Any]]) -> None:
    path = store_path()
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path) or ".", prefix=".explanations-")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        json.dump(entries, f, indent=1, sort_keys=True)
    os.replace(tmp, path)  # atomic: a crash never leaves a half-written file


# ------------------------------------------------------------------ Gemini call

def _model() -> str:
    return os.environ.get("GEMINI_MODEL", "").strip() or DEFAULT_MODEL


def _facts_text(digest: Dict[str, Any]) -> str:
    text = json.dumps(digest, indent=1, default=str)
    if len(text) > MAX_FACTS_CHARS:
        text = text[:MAX_FACTS_CHARS] + "\n... (digest truncated for length)"
    return text


def _generation_config(model: str) -> Dict[str, Any]:
    cfg: Dict[str, Any] = {"temperature": 0.2, "maxOutputTokens": MAX_OUTPUT_TOKENS}
    # Flash models "think" by default and that counts against the output budget, which cut
    # explanations short. A short summary needs no thinking. (Pro models cannot turn it off.)
    if "flash" in model:
        cfg["thinkingConfig"] = {"thinkingBudget": 0}
    return cfg


def _call_gemini(facts_text: str, model: str, api_key: str) -> str:
    """Blocking HTTPS call; run it in a thread."""
    body = {
        "systemInstruction": {"parts": [{"text": INSTRUCTIONS}]},
        "contents": [{"role": "user", "parts": [{"text": "FACTS:\n" + facts_text}]}],
        "generationConfig": _generation_config(model),
    }
    req = urllib.request.Request(
        ENDPOINT.format(model=model),
        data=json.dumps(body).encode("utf-8"),
        headers={"Content-Type": "application/json", "x-goog-api-key": api_key},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=TIMEOUT_S) as resp:
            payload = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        detail = ""
        try:
            detail = json.loads(e.read().decode("utf-8")).get("error", {}).get("message", "")
        except Exception:
            pass
        raise ExplainFailed(f"Gemini returned HTTP {e.code}{': ' + detail if detail else ''}") from None
    except (urllib.error.URLError, TimeoutError) as e:
        raise ExplainFailed(f"Could not reach Gemini ({getattr(e, 'reason', e)})") from None

    try:
        candidate = payload["candidates"][0]
        text = "".join(p.get("text", "") for p in candidate["content"]["parts"]).strip()
        finish = candidate.get("finishReason", "STOP")
    except (KeyError, IndexError, TypeError):
        text, finish = "", None
    if not text:
        reason = (payload.get("promptFeedback") or {}).get("blockReason") or finish or "empty response"
        raise ExplainFailed(f"Gemini gave no explanation ({reason})")
    if finish not in ("STOP", None):
        # MAX_TOKENS, SAFETY, ...: a partial answer would read as a complete one. Don't show or save it.
        raise ExplainFailed(f"Gemini's explanation was incomplete ({finish}); please try again")
    return text


async def explain(artifact_id: str, cert: Dict[str, Any], include_evidence: bool = False) -> Dict[str, Any]:
    """Return {"explanation", "model", "saved_at", "cached", "facts"} for an (already access-checked)
    certificate. include_evidence: the caller may read this record's evidence (admin). The facts are
    returned so the page can draw exact visuals from them rather than from the model's prose."""
    model = _model()
    digest_obj = facts(cert, include_evidence)
    text = _facts_text(digest_obj)
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    key = f"{artifact_id}|{model}|p{PROMPT_VERSION}|{digest}"
    with _lock:
        hit = _load().get(key)
    if hit:
        return {**hit, "cached": True, "facts": digest_obj}

    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not api_key:
        raise ExplainUnavailable("Plain-language explanations are off: set GEMINI_API_KEY on the server.")
    explanation = await asyncio.to_thread(_call_gemini, text, model, api_key)
    entry = {"explanation": explanation, "model": model, "saved_at": int(time.time())}
    with _lock:
        entries = _load()
        entries[key] = entry
        _persist(entries)
    return {**entry, "cached": False, "facts": digest_obj}

"""
HEDWIG audit-explain add-on: a small service beside the HEDWIG server.

The browser script (static/audit-explain.js, served at /audit-explain.js) adds an Explain button
next to each signed audit record. It fetches the record from HEDWIG's own GET /api/audit/{id}
with the viewer's session (so HEDWIG applies its access rules), posts it here, and shows the
plain-language explanation with visuals and HTML/PDF export. Nothing here imports HEDWIG code.

    python service.py            # listens on 127.0.0.1:8010 by default

Environment:
    GEMINI_API_KEY      Google AI Studio key (required for new explanations)
    GEMINI_MODEL        default gemini-2.5-flash
    ALLOWED_ORIGINS     comma-separated HEDWIG page origins allowed to call this service
                        (default: http://localhost:8000, http://127.0.0.1:8000, http://0.0.0.0:8000)
    HOST / PORT         default 127.0.0.1 / 8010 (keep it local: anyone who can reach it can use your quota)
    HEDWIG_EXPLANATIONS where explanations are saved (default data/audit_explanations.json)
"""
import json
import os
from pathlib import Path
from typing import Any, Dict

from fastapi import FastAPI, HTTPException, Request
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, JSONResponse

import explainer

HERE = Path(__file__).resolve().parent
MAX_BODY_BYTES = 2_000_000
NOTICE = "Generated by Google Gemini from this audit record. The signed record is authoritative."
DEFAULT_ORIGINS = "http://localhost:8000,http://127.0.0.1:8000,http://0.0.0.0:8000"

app = FastAPI(title="HEDWIG audit-explain add-on", docs_url=None, redoc_url=None)
app.add_middleware(
    CORSMiddleware,
    allow_origins=[o.strip() for o in os.environ.get("ALLOWED_ORIGINS", DEFAULT_ORIGINS).split(",") if o.strip()],
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type"],
)


def _artifact_id(record: Dict[str, Any]) -> str:
    for key in ("transmission_id", "incident_id", "artifact_id", "reset_id", "probe_id"):
        if isinstance(record.get(key), str) and record[key]:
            return record[key]
    raise HTTPException(400, "The record has no id")


@app.get("/health")
async def health():
    return {"ok": True, "gemini_configured": bool(os.environ.get("GEMINI_API_KEY", "").strip()),
            "model": explainer._model()}


@app.get("/audit-explain.js")
async def script():
    return FileResponse(HERE / "static" / "audit-explain.js", media_type="text/javascript",
                        headers={"Cache-Control": "no-cache"})


@app.post("/explain")
async def explain(request: Request):
    body = await request.body()
    if len(body) > MAX_BODY_BYTES:
        raise HTTPException(413, "Audit record too large")
    try:
        cert = json.loads(body)
    except ValueError:
        raise HTTPException(400, "Body must be the JSON audit record from GET /api/audit/{id}")
    if not (isinstance(cert, dict) and isinstance(cert.get("record"), dict)
            and str(cert.get("format", "")).startswith("hedwig-audit")):
        raise HTTPException(400, "Not a HEDWIG audit record")
    artifact_id = _artifact_id(cert["record"])
    # HEDWIG only includes evidence for viewers allowed to see it (admins), so its presence
    # is what decides whether per-route details may be used.
    include_evidence = isinstance(cert.get("evidence"), dict)
    try:
        result = await explainer.explain(artifact_id, cert, include_evidence=include_evidence)
    except explainer.ExplainUnavailable as e:
        raise HTTPException(503, str(e))
    except explainer.ExplainFailed as e:
        raise HTTPException(502, str(e))
    return JSONResponse({"artifact_id": artifact_id, "kind": cert["record"].get("kind"), **result, "notice": NOTICE})


if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host=os.environ.get("HOST", "127.0.0.1"), port=int(os.environ.get("PORT", "8010")))
